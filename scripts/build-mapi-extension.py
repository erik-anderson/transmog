"""Regenerate the MAPI extension's static JavaScript; never invoked by app startup."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

from mapi_reference import BUILD, ROOT, VENDOR, WORK, dotnet, headless_sources, verify_sources

COMPILER_VERSION = "26.10.6985"
BCL_VERSION = "26.9.5840"
PACKAGES = WORK / "packages"
OUTPUT = ROOT / "extensions/mapi/generated/parser.js"


def compile_parser() -> tuple[bytes, dict]:
    receipt = verify_sources()
    sources = {name: (VENDOR / "Source" / name).read_text(encoding="utf-8-sig") for name in receipt["files"]
               if name != "Parsers/BaseStructure.cs"}
    sources.update(headless_sources())
    sources["Headless.cs"] = (BUILD / "Headless.cs").read_text(encoding="utf-8-sig")
    sources["Primitives.cs"] = (BUILD / "Primitives.cs").read_text(encoding="utf-8-sig")
    WORK.mkdir(parents=True, exist_ok=True)
    inventory = WORK / "compiler-input.json"
    inventory.write_text(json.dumps(sources, sort_keys=True), encoding="utf-8")
    environment = dict(os.environ, NUGET_PACKAGES=str(PACKAGES))
    project = BUILD / "Compiler.csproj"
    subprocess.run([dotnet(), "build", str(project), "--configuration", "Release", "--nologo", "-p:RestoreLockedMode=true"], cwd=ROOT, env=environment, check=True)
    raw = WORK / "parser.raw.js"
    bcl = PACKAGES / f"transpose.bcl/{BCL_VERSION}/lib/netstandard2.0/Transpose.dll"
    result = subprocess.run([dotnet(), str(WORK / "Compiler-bin/Release/net10.0/Compiler.dll"), str(inventory), str(raw), str(bcl)],
                            cwd=ROOT, env=environment, check=True, capture_output=True, text=True, encoding="utf-8", timeout=120)
    adaptations = json.loads(result.stdout)
    javascript = raw.read_text(encoding="utf-8-sig")
    inventory_digest = hashlib.sha256(json.dumps(receipt, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()
    # The web compiler emits a wall-clock cache-buster. Extensions have immutable
    # content identities and no Require loader, so use the pinned source identity.
    javascript, count = re.subn(r'(Transpose.Require && Transpose.Require.cacheBust && Transpose.Require.cacheBust\(")[a-z0-9]+("\);)',
                                lambda match: match[1] + inventory_digest + match[2], javascript)
    if count != 1:
        raise ValueError("The pinned runtime cache-buster adaptation changed")
    # Exact pinned-runtime adaptations: disable unused facilities, never weaken
    # the host AST policy or V8's string code-generation prohibition.
    for expression in ['new Function("" + callback)', 'new Function("u", "return import(u);")',
                       'new Function(args, "return " + expression)', 'new Function(expr[1], "return " + expr[2])']:
        if javascript.count(expression) != 1:
            raise ValueError("The pinned runtime code-generation adaptation changed")
        javascript = javascript.replace(expression, '(()=>{throw new Error("Runtime string compilation is unavailable");})()')
    resolver = 'Function("return this")()'
    if javascript.count(resolver) != 1:
        raise ValueError("The pinned runtime global resolver changed")
    javascript = javascript.replace(resolver, "globalThis")
    javascript = ("// Generated by scripts/build-mapi-extension.py. Preserve upstream notices.\n"
                  "// Function's intrinsic identity is used only by runtime type helpers; string compilation stays disabled.\n"
                  "const Function=(function(){}).constructor;const self=globalThis;\n" + javascript
                  + "\n// MAPI binary fields are little-endian, independently of the BCL runtime's host default.\nSystem.BitConverter.IsLittleEndian=true;\n")
    data = javascript.encode("utf-8")
    return data, {"revision": receipt["revision"], "compiler": COMPILER_VERSION, "bcl": BCL_VERSION,
                  "sourceInventorySha256": inventory_digest,
                  "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data), **adaptations}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Regenerate and compare, without changing committed output")
    arguments = parser.parse_args()
    data, receipt = compile_parser()
    receipt_path = OUTPUT.parent / "build-receipt.json"
    encoded = (json.dumps(receipt, sort_keys=True, indent=2) + "\n").encode("utf-8")
    if arguments.check:
        if OUTPUT.read_bytes() != data or receipt_path.read_bytes() != encoded:
            raise SystemExit("Generated MAPI parser is stale")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(data)
        receipt_path.write_bytes(encoded)
    print(f'Verified static MAPI JavaScript: {len(data):,} bytes, {receipt["enums"]} enum definitions')


if __name__ == "__main__":
    main()
